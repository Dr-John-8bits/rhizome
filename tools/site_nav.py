# Writes the same menu into every page of the site (between the <!-- menu --> markers): python3 tools/site_nav.py
from pathlib import Path
import re
R=Path(__file__).resolve().parents[1]/'site'
# Rhizome's site: the home page (with the simulator) and the manual; Monades' manual (monades/manuel/) keeps its own.
ITEMS=[('Accueil',''),('Simulateur','#jouer'),("Mode d'emploi",'manuel/'),("Monades (pages héritées)",'monades/manuel/'),
       ('Feuille de route','https://github.com/Dr-John-8bits/rhizome/blob/main/docs/rhizome/FEUILLE-DE-ROUTE.md'),('Sources','https://github.com/Dr-John-8bits/rhizome')]
PAGES=['index.html','manuel/index.html']
for page in PAGES:
 up='../'*page.count('/');here=page[:-len('index.html')]
 links=[]
 for name,href in ITEMS:
  if href.startswith('http'):links.append(f'<li><a href="{href}">{name}</a></li>');continue
  url=(up or './')+href if not href.startswith('#') else (up or './')+href # the simulator lives on the home page
  cur=' aria-current="page"' if href==here and not href.startswith('#') else ''
  links.append(f'<li><a href="{url}"{cur}>{name}</a></li>')
 block=('<!-- menu: generated by tools/site_nav.py -->\n  <nav class="menu" aria-label="Menu"><button class="menu-btn" type="button" aria-expanded="false" aria-controls="menu-list">Menu</button>'
        '<ul id="menu-list">'+''.join(links)+'</ul></nav>\n  <!-- /menu -->')
 f=R/page;s=f.read_text();s,n=re.subn(r'<!-- menu:.*?<!-- /menu -->',lambda m:block,s,flags=re.S);assert n==1,f'markers missing in {f}'
 f.write_text(s)
print('menu written in',len(PAGES),'pages')
